import turtle

op=turtle.Turtle()
wn=turtle.Screen()

def cir(size):
    op.penup()
    op.setheading(0)
    op.setpos(0,-size)
    op.pendown()
    op.begin_fill()
    op.circle(size)
    op.end_fill()
    op.home()
def petal(size,angle):
    op.begin_fill()
    for i in range(2):
        op.circle(size,angle)
        op.left(180-angle)
    op.end_fill()
def flower(n,size,angle):
    for i in range(n):
        petal(size,angle)
        op.left(360.0/n)
